export const VALUE_LETTERS = [...new Set(VALUES_LIST.map(v => v.label[0].toUpperCase()))].sort();

// Helper to find a value by id (works for both standard and custom values)
export function getValueLabel(id: string, customValues: string[] = []): string {
  const found = VALUES_LIST.find(v => v.id === id);
  if (found) return found.label;
  // Custom values use "custom-0", "custom-1", "custom-2" as ids
  const customIndex = id.startsWith('custom-') ? parseInt(id.split('-')[1]) : -1;
  if (customIndex >= 0 && customIndex < customValues.length) {
    return customValues[customIndex];
  }
  return id;
}
